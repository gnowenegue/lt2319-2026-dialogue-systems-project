import { describe, expect, it } from 'vitest';
import { CircularAudioBuffer } from '../circular-buffer';
import { DEFAULT_PRE_ROLL_CAPACITY } from '../constants';

describe('CircularAudioBuffer', () => {
  it('initializes with correct capacity and zero size', () => {
    const ring = new CircularAudioBuffer(100);
    expect(ring.capacity).toBe(100);
    expect(ring.size).toBe(0);
    expect(ring.getBuffer()).toEqual(new Int16Array(0));
  });

  it('throws error if capacity is zero or negative', () => {
    expect(() => new CircularAudioBuffer(0)).toThrow();
    expect(() => new CircularAudioBuffer(-10)).toThrow();
  });

  it('handles empty writes without modifying state', () => {
    const ring = new CircularAudioBuffer(100);
    ring.write(new Int16Array(0));
    expect(ring.size).toBe(0);
    expect(ring.getBuffer().length).toBe(0);
  });

  it('stores samples sequentially before capacity is reached', () => {
    const ring = new CircularAudioBuffer(10);
    const chunk1 = new Int16Array([1, 2, 3]);
    const chunk2 = new Int16Array([4, 5]);

    ring.write(chunk1);
    expect(ring.size).toBe(3);
    expect(Array.from(ring.getBuffer())).toEqual([1, 2, 3]);

    ring.write(chunk2);
    expect(ring.size).toBe(5);
    expect(Array.from(ring.getBuffer())).toEqual([1, 2, 3, 4, 5]);
  });

  it('maintains chronological order when buffer wraps around', () => {
    // configure buffer to hold at most 5 samples
    const ring = new CircularAudioBuffer(5);

    // write [1, 2, 3] so the buffer currently contains [1, 2, 3]
    ring.write(new Int16Array([1, 2, 3]));
    expect(Array.from(ring.getBuffer())).toEqual([1, 2, 3]);

    // write [4, 5] to fill the buffer completely to its capacity of 5
    ring.write(new Int16Array([4, 5]));
    expect(ring.size).toBe(5);
    expect(Array.from(ring.getBuffer())).toEqual([1, 2, 3, 4, 5]);

    // write [6, 7], which wraps around index 0 and overwrites the oldest two samples [1, 2]
    // samples in chronological order should now be [3, 4, 5, 6, 7]
    ring.write(new Int16Array([6, 7]));
    expect(ring.size).toBe(5);
    expect(Array.from(ring.getBuffer())).toEqual([3, 4, 5, 6, 7]);

    // write [8], overwriting oldest sample 3 to leave [4, 5, 6, 7, 8]
    ring.write(new Int16Array([8]));
    expect(Array.from(ring.getBuffer())).toEqual([4, 5, 6, 7, 8]);
  });

  it('handles write larger than capacity by keeping trailing samples', () => {
    const ring = new CircularAudioBuffer(4);
    // write 6 samples into a buffer that can only hold 4
    ring.write(new Int16Array([10, 20, 30, 40, 50, 60]));

    expect(ring.size).toBe(4);
    // the buffer should keep only the most recent 4 samples: [30, 40, 50, 60]
    expect(Array.from(ring.getBuffer())).toEqual([30, 40, 50, 60]);
  });

  it('handles continuous small chunks (e.g. 128 samples) with 500ms pre-roll', () => {
    const capacity = DEFAULT_PRE_ROLL_CAPACITY; // 8,000 samples represent 500ms of audio recorded at 16 kHz
    const ring = new CircularAudioBuffer(capacity);

    // simulate 100 streaming audio chunks of 128 samples each (12,800 total samples)
    let sampleCounter = 0;
    for (let c = 0; c < 100; c++) {
      const chunk = new Int16Array(128);
      for (let i = 0; i < 128; i++) {
        chunk[i] = sampleCounter++ % 32767;
      }
      ring.write(chunk);
    }

    expect(ring.size).toBe(capacity);
    const buffered = ring.getBuffer();
    expect(buffered.length).toBe(capacity);

    // the final buffer should hold exactly the last 8,000 samples generated by `sampleCounter`
    const expectedStart = sampleCounter - capacity;
    for (let i = 0; i < capacity; i++) {
      expect(buffered[i]).toBe((expectedStart + i) % 32767);
    }
  });

  it('clears all stored samples and resets head on clear()', () => {
    const ring = new CircularAudioBuffer(5);
    ring.write(new Int16Array([1, 2, 3, 4, 5]));
    expect(ring.size).toBe(5);

    ring.clear();
    expect(ring.size).toBe(0);
    expect(ring.getBuffer().length).toBe(0);

    // verify that new samples can be added normally after calling `clear()`
    ring.write(new Int16Array([99, 100]));
    expect(ring.size).toBe(2);
    expect(Array.from(ring.getBuffer())).toEqual([99, 100]);
  });
});
